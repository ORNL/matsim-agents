#!/usr/bin/env python3
"""Rank model outputs from eval_six_models_search_prompt.py.

Reads a JSON report produced by scripts/eval_six_models_search_prompt.py,
computes a weighted score for each model, writes a CSV leaderboard, and
prints a concise ranking to stdout.
"""

from __future__ import annotations

import argparse
import csv
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any


@dataclass
class Weights:
    keyword: float
    composition: float
    length: float
    latency: float


def _safe_float(value: Any, default: float = 0.0) -> float:
    try:
        return float(value)
    except Exception:
        return default


def _clamp01(x: float) -> float:
    return max(0.0, min(1.0, x))


def _latency_score(latency_sec: float, pivot_sec: float) -> float:
    if latency_sec <= 0:
        return 1.0
    if pivot_sec <= 0:
        return 0.0
    # 1.0 at 0s, 0.5 near pivot, asymptotically approaches 0.
    return 1.0 / (1.0 + (latency_sec / pivot_sec))


def _score_row(
    row: dict[str, Any],
    weights: Weights,
    min_chars: int,
    comp_target: int,
    latency_pivot_sec: float,
) -> dict[str, Any]:
    status = str(row.get("status", ""))
    if status != "ok":
        return {
            "score": 0.0,
            "keyword_cov": 0.0,
            "composition_score": 0.0,
            "length_score": 0.0,
            "latency_score": 0.0,
        }

    keyword_hits = row.get("keyword_hits") or {}
    cov = (
        sum(1 for v in keyword_hits.values() if bool(v)) / len(keyword_hits)
        if isinstance(keyword_hits, dict) and keyword_hits
        else 0.0
    )

    comp_count = len(row.get("compositions") or [])
    comp_score = _clamp01(comp_count / max(1, comp_target))

    chars = int(row.get("response_chars") or 0)
    len_score = _clamp01(chars / max(1, min_chars))

    latency = _safe_float(row.get("latency_sec"), default=0.0)
    lat_score = _latency_score(latency, latency_pivot_sec)

    score = (
        weights.keyword * cov
        + weights.composition * comp_score
        + weights.length * len_score
        + weights.latency * lat_score
    )

    return {
        "score": round(score, 6),
        "keyword_cov": round(cov, 6),
        "composition_score": round(comp_score, 6),
        "length_score": round(len_score, 6),
        "latency_score": round(lat_score, 6),
    }


def rank_report(
    report: dict[str, Any],
    *,
    weights: Weights,
    min_chars: int,
    comp_target: int,
    latency_pivot_sec: float,
) -> list[dict[str, Any]]:
    results = report.get("results")
    if not isinstance(results, list):
        raise ValueError("Input JSON missing 'results' list.")

    ranked: list[dict[str, Any]] = []
    for row in results:
        if not isinstance(row, dict):
            continue
        metrics = _score_row(
            row,
            weights=weights,
            min_chars=min_chars,
            comp_target=comp_target,
            latency_pivot_sec=latency_pivot_sec,
        )
        merged = dict(row)
        merged.update(metrics)
        ranked.append(merged)

    ranked.sort(
        key=lambda r: (
            _safe_float(r.get("score"), 0.0),
            -_safe_float(r.get("latency_sec"), 0.0),
        ),
        reverse=True,
    )

    for idx, row in enumerate(ranked, start=1):
        row["rank"] = idx

    return ranked


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Rank model eval JSON and export a CSV leaderboard."
    )
    parser.add_argument(
        "--input",
        type=Path,
        required=True,
        help="Path to model-eval JSON generated by eval_six_models_search_prompt.py.",
    )
    parser.add_argument(
        "--out-csv",
        type=Path,
        default=None,
        help="Output CSV path. Defaults to <input-stem>-leaderboard.csv.",
    )
    parser.add_argument(
        "--out-json",
        type=Path,
        default=None,
        help="Optional path to write ranked JSON payload.",
    )
    parser.add_argument(
        "--weight-keyword",
        type=float,
        default=0.45,
        help="Weight for keyword coverage metric.",
    )
    parser.add_argument(
        "--weight-composition",
        type=float,
        default=0.20,
        help="Weight for extracted composition count metric.",
    )
    parser.add_argument(
        "--weight-length",
        type=float,
        default=0.20,
        help="Weight for response length adequacy metric.",
    )
    parser.add_argument(
        "--weight-latency",
        type=float,
        default=0.15,
        help="Weight for latency metric (higher is faster).",
    )
    parser.add_argument(
        "--min-chars",
        type=int,
        default=600,
        help="Character count that receives full length score.",
    )
    parser.add_argument(
        "--comp-target",
        type=int,
        default=3,
        help="Composition count that receives full composition score.",
    )
    parser.add_argument(
        "--latency-pivot-sec",
        type=float,
        default=20.0,
        help="Latency where latency score is roughly 0.5.",
    )
    return parser


def _write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "rank",
        "name",
        "provider",
        "model",
        "status",
        "score",
        "keyword_cov",
        "composition_score",
        "length_score",
        "latency_score",
        "latency_sec",
        "response_chars",
        "compositions",
        "error",
    ]
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            out = {k: row.get(k) for k in fieldnames}
            out["compositions"] = ";".join(row.get("compositions") or [])
            writer.writerow(out)


def main() -> int:
    args = _build_parser().parse_args()

    data = json.loads(args.input.read_text())

    weights = Weights(
        keyword=args.weight_keyword,
        composition=args.weight_composition,
        length=args.weight_length,
        latency=args.weight_latency,
    )

    total_weight = weights.keyword + weights.composition + weights.length + weights.latency
    if abs(total_weight - 1.0) > 1e-9:
        raise ValueError(
            f"Weights must sum to 1.0, got {total_weight:.6f}. "
            "Adjust --weight-* arguments."
        )

    ranked = rank_report(
        data,
        weights=weights,
        min_chars=args.min_chars,
        comp_target=args.comp_target,
        latency_pivot_sec=args.latency_pivot_sec,
    )

    out_csv = args.out_csv
    if out_csv is None:
        out_csv = args.input.with_name(f"{args.input.stem}-leaderboard.csv")

    _write_csv(ranked, out_csv)

    print("Leaderboard")
    for row in ranked:
        print(
            f"{row['rank']:>2}. {row.get('name')} "
            f"score={_safe_float(row.get('score')):.3f} "
            f"status={row.get('status')} "
            f"lat={_safe_float(row.get('latency_sec')):.2f}s"
        )

    print(f"CSV written: {out_csv}")

    if args.out_json is not None:
        args.out_json.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "source": str(args.input),
            "weights": {
                "keyword": weights.keyword,
                "composition": weights.composition,
                "length": weights.length,
                "latency": weights.latency,
            },
            "min_chars": args.min_chars,
            "comp_target": args.comp_target,
            "latency_pivot_sec": args.latency_pivot_sec,
            "ranked": ranked,
        }
        args.out_json.write_text(json.dumps(payload, indent=2))
        print(f"Ranked JSON written: {args.out_json}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
