#!/bin/bash
# Build OpenMC on Frontier with every artifact confined to <repo>/.hpc-build/frontier/openmc/:
#   src/ (clone and C++ build), venv/ (Python 3.11 environment), data/ (cross sections, chain,
#   build record) and activate.sh (environment for jobs). Nothing is written elsewhere.
#
# Usage (login node, internet needed, no allocation):
#   bash deployments/frontier/setup/build-openmc-frontier.sh
# Env:  OPENMC_DATA_DIR     reuse an existing nuclear-data directory instead of downloading 3.4 GB
#       OPENMC_BASE_PYTHON  Python 3.11 used to create the venv (default: <repo>/.venv, else python3)
#       OPENMC_HDF5_ROOT    HDF5 prefix (default: the Cray GNU 12.3 build below)
#       the other OPENMC_* variables of ../../common/setup/build-openmc.sh are passed through.
# Needs the Cray GCC 12.3 toolchain; the system g++ (7.5) cannot build OpenMC.

set -euo pipefail

SCRIPT_DIR="$(CDPATH= cd -P -- "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
REPO="$(CDPATH= cd -P -- "${SCRIPT_DIR}/../../.." && pwd -P)"
ROOT="${REPO}/.hpc-build/frontier/openmc"

GCC_BIN=/opt/cray/pe/gcc-native/12/bin
HDF5_DEFAULT=/opt/cray/pe/hdf5/1.14.3.9/gnu/12.3
RUNTIME_LIBS="${HDF5_DEFAULT}/lib:/opt/cray/pe/gcc-native/12/snos/lib64:/opt/cray/pe/mpich/9.1.0/ofi/crayclang/20.0/lib"

[[ -x "${GCC_BIN}/g++" ]] || { echo "Cray GCC 12 not found at ${GCC_BIN}; this script is for Frontier" >&2; exit 2; }

export OPENMC_CXX="${OPENMC_CXX:-${GCC_BIN}/g++}"
export OPENMC_CC="${OPENMC_CC:-${GCC_BIN}/gcc}"
export OPENMC_HDF5_ROOT="${OPENMC_HDF5_ROOT:-${HDF5_DEFAULT}}"
export OPENMC_DIR="${OPENMC_DIR:-${ROOT}/src}"
export OPENMC_DATA_DIR="${OPENMC_DATA_DIR:-${ROOT}/data}"
export OPENMC_RUNTIME_LIBS="${OPENMC_RUNTIME_LIBS:-${RUNTIME_LIBS}}"
export PIP_CERT="${PIP_CERT:-/etc/ssl/ca-bundle.pem}"
# XALT's exit hook segfaults after the Python/HDF5 libraries are loaded.
export XALT_EXECUTABLE_TRACKING=no

if [[ ! -x "${ROOT}/venv/bin/python" ]]; then
    BASE_PY="${OPENMC_BASE_PYTHON:-${REPO}/.venv/bin/python}"
    [[ -x "${BASE_PY}" ]] || BASE_PY="$(command -v python3)"
    "${BASE_PY}" -m venv "${ROOT}/venv"
fi
# shellcheck disable=SC1091
source "${ROOT}/venv/bin/activate"

bash "${SCRIPT_DIR}/../../common/setup/build-openmc.sh"

cat > "${ROOT}/activate.sh" <<EOF
# Generated by build-openmc-frontier.sh; source it before running OpenMC on Frontier.
source "${ROOT}/venv/bin/activate"
export OPENMC_CROSS_SECTIONS="${OPENMC_DATA_DIR}/endfb-viii.0-hdf5/cross_sections.xml"
export OPENMC_CHAIN_FILE="${OPENMC_DATA_DIR}/chain_endfb80_pwr.xml"
export LD_LIBRARY_PATH="${OPENMC_RUNTIME_LIBS}\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"
export XALT_EXECUTABLE_TRACKING=no
EOF
echo "Environment for jobs: source ${ROOT}/activate.sh"
