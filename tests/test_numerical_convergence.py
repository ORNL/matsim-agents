def test_workflow_plan_collect_analyse_report_and_restart(config_path, tmp_path):
    config = nc.load_config(config_path)
    runs = nc.plan(config)
    assert len(runs) == 6
    assert all(r.input_path.is_file() for r in runs)
    # A rerun is deterministic: identical keys.
    assert [r.key for r in nc.plan(config)] == [r.key for r in runs]

    log = KeyedResultLog(Path(config.out_dir) / "results.jsonl")
    sent: list[str] = []
    jobs = nc.submit(runs, log, lambda run: sent.append(run.key) or "1")
    assert len(jobs) == 6 and len(sent) == 6

    for r in runs:
        energy = -100.0 if r.scan == "cutoff" else -200.0
        r.output_path.write_text(pw_out(energy))
    collected = nc.collect(runs, log)
    assert collected["pending"] == 0 and collected["versions"] == ["7.3"]
    # Finished runs are not resubmitted.
    assert nc.submit(runs, log, lambda run: pytest.fail("resubmitted")) == {}

    data = nc.report(config, nc.analyse(config, runs, log), collected)
    assert data["status"] == "qualified" and data["label"] == nc.SOFTWARE_ONLY
    assert (Path(config.out_dir) / "report.md").is_file()
    cutoff = next(s for s in data["scans"] if s["parameter"] == "cutoff")
    assert cutoff["selected_value"] == [40, 320]


def test_scheduler_completed_without_output_is_not_success(config_path):
    config = nc.load_config(config_path)
    runs = nc.plan(config)
    log = KeyedResultLog(Path(config.out_dir) / "results.jsonl")
    collected = nc.collect(runs, log)
    assert collected["pending"] == len(runs)
    data = nc.report(config, nc.analyse(config, runs, log), collected)
    assert data["status"] == "incomplete"


